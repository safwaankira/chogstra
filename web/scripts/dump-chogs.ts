// Dumps Chog Genesis metadata for every token into web/data/chogs.json,
// then writes a trait summary to web/data/traits-summary.md.
//
// Run from web/:  node scripts/dump-chogs.ts
// Safe to re-run: tokens already in chogs.json are skipped.

import { mkdir, readFile, rename, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createPublicClient, http, parseAbi } from "viem";
import { monad } from "viem/chains";

const RPC_URL = "https://rpc.monad.xyz";
const CHOG_GENESIS = "0xc96d31f8626c6d03fae5dcd3d61e3fb9f4a73763";
const FIRST_ID = 1;
const LAST_ID = 1969;
const CONCURRENCY = 10;
const MAX_ATTEMPTS = 4; // first try + 3 retries
const SAVE_EVERY = 50;

// ipfs.io, dweb.link, w3s.link and nftstorage.link all end at ipfs.io, which
// answers 429 to plain HTTP fetches; Pinata rate-limits after ~100 requests.
// Filebase held up, so it goes first. Retries rotate through the list.
const GATEWAYS = (process.env.IPFS_GATEWAYS ?? "https://ipfs.filebase.io/ipfs/,https://gateway.pinata.cloud/ipfs/")
  .split(",")
  .map((g) => g.trim())
  .filter(Boolean);

const DATA_DIR = join(dirname(fileURLToPath(import.meta.url)), "..", "data");
const OUT_FILE = join(DATA_DIR, "chogs.json");
const SUMMARY_FILE = join(DATA_DIR, "traits-summary.md");

type Chog = {
  tokenId: number;
  name: string;
  image: string;
  traits: Record<string, string>;
};

type Failure = { tokenId: number; error: string };

const abi = parseAbi(["function tokenURI(uint256 tokenId) view returns (string)"]);
const client = createPublicClient({ chain: monad, transport: http(RPC_URL) });

function toGatewayUrl(uri: string, attempt: number): string {
  if (!uri.startsWith("ipfs://")) return uri;
  const path = uri.slice("ipfs://".length).replace(/^ipfs\//, "");
  return GATEWAYS[attempt % GATEWAYS.length] + path;
}

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

async function withRetry<T>(label: string, fn: (attempt: number) => Promise<T>): Promise<T> {
  let lastError: unknown;
  for (let attempt = 0; attempt < MAX_ATTEMPTS; attempt++) {
    try {
      return await fn(attempt);
    } catch (err) {
      lastError = err;
      if (attempt < MAX_ATTEMPTS - 1) await sleep(1000 * 2 ** attempt);
    }
  }
  const msg = lastError instanceof Error ? lastError.message : String(lastError);
  throw new Error(`${label}: ${msg.split("\n")[0]}`);
}

async function fetchChog(tokenId: number): Promise<Chog> {
  const uri = await withRetry("tokenURI", () =>
    client.readContract({ address: CHOG_GENESIS, abi, functionName: "tokenURI", args: [BigInt(tokenId)] }),
  );

  const meta = await withRetry("metadata", async (attempt) => {
    const res = await fetch(toGatewayUrl(uri, attempt), { signal: AbortSignal.timeout(30_000) });
    if (!res.ok) throw new Error(`HTTP ${res.status} from ${new URL(res.url).host}`);
    return (await res.json()) as {
      name?: string;
      image?: string;
      attributes?: { trait_type?: string; value?: unknown }[];
    };
  });

  if (typeof meta.name !== "string" || typeof meta.image !== "string" || !Array.isArray(meta.attributes)) {
    throw new Error(`metadata: missing name, image or attributes (${uri})`);
  }

  const traits: Record<string, string> = {};
  for (const attr of meta.attributes) {
    if (attr.trait_type) traits[attr.trait_type] = String(attr.value);
  }
  return { tokenId, name: meta.name, image: meta.image, traits };
}

async function loadExisting(): Promise<Map<number, Chog>> {
  try {
    const list = JSON.parse(await readFile(OUT_FILE, "utf8")) as Chog[];
    return new Map(list.map((c) => [c.tokenId, c]));
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === "ENOENT") return new Map();
    throw err;
  }
}

async function save(chogs: Map<number, Chog>) {
  const list = [...chogs.values()].sort((a, b) => a.tokenId - b.tokenId);
  const tmp = OUT_FILE + ".tmp";
  await writeFile(tmp, JSON.stringify(list, null, 2) + "\n");
  await rename(tmp, OUT_FILE);
}

function buildSummary(chogs: Map<number, Chog>, failures: Failure[]): string {
  const counts = new Map<string, Map<string, number>>();
  const traitTypeCount = new Map<string, number>();
  for (const chog of chogs.values()) {
    for (const [type, value] of Object.entries(chog.traits)) {
      if (!counts.has(type)) counts.set(type, new Map());
      const values = counts.get(type)!;
      values.set(value, (values.get(value) ?? 0) + 1);
      traitTypeCount.set(type, (traitTypeCount.get(type) ?? 0) + 1);
    }
  }

  const total = LAST_ID - FIRST_ID + 1;
  const missing: number[] = [];
  for (let id = FIRST_ID; id <= LAST_ID; id++) if (!chogs.has(id)) missing.push(id);

  const lines: string[] = [
    "# Chog Genesis trait summary",
    "",
    `Generated by \`web/scripts/dump-chogs.ts\` from \`web/data/chogs.json\` on ${new Date().toISOString().slice(0, 10)}.`,
    `Contract ${CHOG_GENESIS} on Monad mainnet (chain 143).`,
    "",
    `- Tokens saved: **${chogs.size} / ${total}**`,
    `- Failed this run: **${failures.length}**`,
    `- Missing from chogs.json: **${missing.length}**${missing.length ? ` (${missing.join(", ")})` : ""}`,
    "",
  ];

  if (failures.length) {
    lines.push("## Failures", "");
    for (const f of failures) lines.push(`- tokenId ${f.tokenId}: ${f.error}`);
    lines.push("");
  }

  lines.push(`## Trait types (${counts.size})`, "");
  for (const [type, values] of counts) {
    const present = traitTypeCount.get(type)!;
    const note = present < chogs.size ? `, present on ${present} tokens` : "";
    lines.push(`### ${type} (${values.size} values${note})`, "", "| Value | Count |", "| --- | ---: |");
    const sorted = [...values].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
    for (const [value, count] of sorted) lines.push(`| ${value} | ${count} |`);
    lines.push("");
  }
  return lines.join("\n");
}

async function main() {
  await mkdir(DATA_DIR, { recursive: true });
  const chogs = await loadExisting();

  const todo: number[] = [];
  for (let id = FIRST_ID; id <= LAST_ID; id++) if (!chogs.has(id)) todo.push(id);
  console.log(`Already have ${chogs.size}, fetching ${todo.length} (concurrency ${CONCURRENCY})`);

  const failures: Failure[] = [];
  let done = 0;
  let next = 0;

  async function worker() {
    while (next < todo.length) {
      const tokenId = todo[next++];
      try {
        chogs.set(tokenId, await fetchChog(tokenId));
      } catch (err) {
        failures.push({ tokenId, error: err instanceof Error ? err.message : String(err) });
      }
      done++;
      if (done % SAVE_EVERY === 0) {
        await save(chogs);
        console.log(`  ${done}/${todo.length} (${failures.length} failed)`);
      }
    }
  }

  await Promise.all(Array.from({ length: CONCURRENCY }, worker));
  await save(chogs);

  failures.sort((a, b) => a.tokenId - b.tokenId);
  const summary = buildSummary(chogs, failures);
  await writeFile(SUMMARY_FILE, summary);
  console.log("\n" + summary);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
