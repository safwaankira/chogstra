// Copies the Chogstra ABI from Foundry's build output into web/lib/abi/chogstra.ts.
// Run after contract changes:  (cd contracts && forge build) && node web/scripts/gen-abi.mjs

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const artifact = join(web, "..", "contracts", "out", "Chogstra.sol", "Chogstra.json");
const out = join(web, "lib", "abi", "chogstra.ts");

const { abi } = JSON.parse(readFileSync(artifact, "utf8"));
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  "// Generated by web/scripts/gen-abi.mjs from contracts/out/Chogstra.sol/Chogstra.json. Do not edit.\n" +
    `export const chogstraAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
console.log(`Wrote ${out} (${abi.length} entries)`);
